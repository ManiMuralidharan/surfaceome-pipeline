source('R/utils_data.R');source('R/utils_metrics.R');source('R/utils_plotting.R');source('R/mod_prioritize.R');source('R/mod_ml.R')
stopifnot(all(c('shiny','bslib','ggplot2','DT','pROC','PRROC','limma') %in% rownames(installed.packages())))
set.seed(8)
m<-matrix(rpois(40*12,20),40,12,dimnames=list(paste0('P',1:40),paste0('S',1:12)))
md<-data.frame(sample_id=colnames(m),group=rep(c('Normal','Tumor'),each=6))
cl<-normalize_adt(m)
stopifnot(identical(dim(cl),dim(m)),max(abs(colMeans(cl)))<1e-8)
d<-fit_differential(cl,md)
stopifnot(nrow(d)==40,all(c('logFC','adj.P.Val') %in% names(d)))
ms<-normalize_ms(m)
stopifnot(identical(dim(ms),dim(m)))
p<-data.frame(truth=rep(c(0L,1L),each=50),scoreA=c(runif(50,0,.5),runif(50,.5,1)),scoreB=runif(100))
r<-evaluate_scores(p,B=20)
stopifnot(r$auc>.9,nrow(r$ci)==3,all(c('TP','FP','TN','FN') %in% names(r$confusion)))
integ<-data.frame(feature=paste0('P',1:40),logFC_ADT=runif(40),logFC_MS=runif(40))
ann<-data.frame(feature=integ$feature,surface_evidence=rep(.8,40),normal_tissue_risk=rep(.1,40))
stopifnot(nrow(rank_targets(integ,ann))==40)
ml<-data.frame(cohort=rep(c('A','B','C'),each=80),truth=rep(rep(c(0,1),each=40),3),x=rnorm(240),z=rnorm(240))
out<-run_external_model(ml,c('x','z'),validation='LOCO')
stopifnot(nrow(out)==240,all(c('truth','scoreA','scoreB','fold') %in% names(out)))
# log2 scale check: 4x count increase should give logFC ~2 in ADT
m2<-matrix(rpois(40*12,50),40,12,dimnames=list(paste0('P',1:40),paste0('S',1:12)));m2[1:5,7:12]<-m2[1:5,7:12]*4
d2<-fit_differential(normalize_adt(m2,'logCPM'),md);# CPM rescales library size: 5/40 features x4 -> expected log2FC = 2 - log2(55/40) ~ 1.54
exp_lfc<-2-log2(55/40); stopifnot(all(abs(d2$logFC[match(paste0('P',1:5),d2$feature)]-exp_lfc)<.35))
# CLR is also log2: mean logFC of spiked features should be clearly > 1 (natural-log version would be ~0.7x smaller)
d3<-fit_differential(normalize_adt(m2,'CLR'),md);stopifnot(mean(d3$logFC[match(paste0('P',1:5),d3$feature)])>1.2)
# concordance only for up-up; FDR gate drops non-significant
ig<-data.frame(feature=c('a','b','c'),logFC_ADT=c(1,-1,1),logFC_MS=c(1,-1,1),adj.P.Val_ADT=c(.01,.01,.5),adj.P.Val_MS=c(.01,.01,.5))
an<-data.frame(feature=ig$feature,surface_evidence=.5,normal_tissue_risk=.5)
rk<-rank_targets(ig,an);stopifnot(nrow(rk)==2,rk$concordance[rk$feature=='a']==1,rk$concordance[rk$feature=='b']==0)
cat('All core tests passed\n')
